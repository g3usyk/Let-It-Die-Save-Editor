def t(key, default=None, **kwargs):
    lang = get_language()
    val = TRANSLATIONS.get(lang, {}).get(key)
    if val is None:
        val = TRANSLATIONS.get("en", {}).get(key, default if default is not None else key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val

def get_item_name(item):
    if not item:
        return ""
    lang = get_language()
    if lang in ("en", "zh"):
        return item.get("name_en") or item.get("name_es") or item.get("name") or str(item.get("id", ""))
    else:
        return item.get("name_es") or item.get("name_en") or item.get("name") or str(item.get("id", ""))

def get_item_desc(item):
    if not item:
        return ""
    lang = get_language()
    desc = (item.get("desc_en") if lang in ("en", "zh") else item.get("desc_es")) or item.get("desc_es") or item.get("desc_en") or ""
    if "//" in desc:
        desc = desc.replace("//", "\n")
    return desc

