# -*- coding: utf-8 -*-
"""
Internationalization (i18n) Module for LET IT DIE Save Editor.
Supports dynamic switching between Spanish (es) and English (en).
"""

import os
import sys
import json
import locale

if getattr(sys, "frozen", False):
    BASE_DIR = os.path.dirname(os.path.abspath(sys.executable))
else:
    BASE_DIR = os.path.dirname(os.path.abspath(__file__))

CONFIG_FILE = os.path.join(BASE_DIR, "config.json")

def _detect_system_language():
    try:
        loc = locale.getdefaultlocale()[0] or ""
        if "es" in loc.lower():
            return "es"
        elif "zh" in loc.lower():
            return "zh"
        else:
            return "en"
    except Exception:
        return "en"

_current_language = None

def get_language():
    global _current_language
    if _current_language is None:
        _current_language = load_saved_language()
    return _current_language

def set_language(lang_code):
    global _current_language
    if lang_code in ("es", "en", "zh"):
        _current_language = lang_code
        save_language_preference(lang_code)

def load_saved_language():
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as f:
                cfg = json.load(f)
                lang = cfg.get("language")
                if lang in ("es", "en", "zh"):
                    return lang
        except Exception:
            pass
    return _detect_system_language()

def save_language_preference(lang_code):
    cfg = {}
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as f:
                cfg = json.load(f)
        except Exception:
            cfg = {}
    cfg["language"] = lang_code
    try:
        with open(CONFIG_FILE, "w", encoding="utf-8") as f:
            json.dump(cfg, f, indent=2, ensure_ascii=False)
    except Exception:
        pass

